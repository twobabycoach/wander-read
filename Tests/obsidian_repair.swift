import Foundation
func runObsidianRepairChecks() throws {
    let base=FileManager.default.temporaryDirectory.appendingPathComponent("wander-uri-\(UUID().uuidString)")
    let root=base.appendingPathComponent("我的 研究库"),daily=root.appendingPathComponent("Daily")
    try FileManager.default.createDirectory(at:root.appendingPathComponent(".obsidian"),withIntermediateDirectories:true)
    let file=daily.appendingPathComponent("2023/11/2023-11-11.md")
    try FileManager.default.createDirectory(at:file.deletingLastPathComponent(),withIntermediateDirectories:true)
    try Data("keep note".utf8).write(to:file)
    check(try ObsidianLinks.root(containing:daily).path==root.path,"选中 Daily 子文件夹也能识别真正仓库根目录")
    rejects({_ = try ObsidianLinks.root(containing:base)},"非 Obsidian 文件夹不会被误当仓库")
    let generated=ObsidianLinks.uri(file:file)
    let parsed=URLComponents(string:generated)!
    check(parsed.queryItems?.first(where:{$0.name=="path"})?.value==file.path && !generated.contains("vault="),"新入口使用正确编码的绝对路径，不猜仓库名")
    check(try ObsidianLinks.checkedURL(generated).scheme=="obsidian","现有绝对路径笔记可通过打开前检查")
    rejects({_ = try ObsidianLinks.checkedURL(ObsidianLinks.uri(file:root.appendingPathComponent("missing.md")))},"原笔记缺失时不派发打开，也不记录阅读")
    let special=root.appendingPathComponent("A+B & C.md")
    try Data("special".utf8).write(to:special)
    let specialURI=ObsidianLinks.uri(file:special)
    check(specialURI.contains("%2B") && specialURI.contains("%26") && specialURI.contains("%2F"),"特殊文件名与路径分隔符严格编码，避免加号被解释为空格")
    check(try ObsidianLinks.checkedURL(specialURI).scheme=="obsidian","含加号与空格的笔记可通过存在性检查")
    let broken="obsidian://open?vault=Daily&file=2023/11/2023-11-11"
    check(ObsidianLinks.repair(broken,root:root)==generated,"截图中的错误链接按真实 Daily 文件位置修复")
    check(ObsidianLinks.repair("obsidian://open?vault=Daily&file=../outside",root:root)==nil,"修复拒绝路径穿越")
    check(ObsidianLinks.repair("obsidian://open?vault=Daily&file=missing",root:root)==nil,"未找到原文件时不伪造链接")
    let conflicting=root.appendingPathComponent("2023/11/2023-11-11.md")
    try FileManager.default.createDirectory(at:conflicting.deletingLastPathComponent(),withIntermediateDirectories:true)
    try Data("another".utf8).write(to:conflicting)
    check(ObsidianLinks.repair(broken,root:root)==nil,"找到两个可能目标时保留原链接")
    try FileManager.default.removeItem(at:conflicting)
    let store=ReadingStore(directory:base.appendingPathComponent("data"))
    var item=ReadingItem(title:"旧笔记",target:broken);item.metricValues=["importance":9];item.priorityLocked=true
    check(store.commit {$0.items=[item]},"修复测试建立原有收藏身份")
    let plans=store.repairPreview(root:root)
    store.applyRepairs(plans)
    check(store.library.items[0].target==generated && store.library.items[0].id==item.id && store.library.items[0].metricValues?["importance"]==9 && store.library.items[0].priorityLocked==true,"批量修复只改入口，保留身份、评分和锁定")
    let resumed=ReadingStore(directory:base.appendingPathComponent("data"));resumed.undoRepairs()
    check(resumed.library.items[0].target==broken,"链接修复可跨重启撤销")
    check(try String(contentsOf:file)=="keep note","修复不写入原笔记")
    var profile=ShareProfile();profile.nickname="二宝";profile.bio="顺着问题走";profile.visible=true
    check(store.saveProfile(profile),"个人名片可主动保存")
    check(ReadingStore(directory:base.appendingPathComponent("data")).library.preferences.shareProfile?.nickname=="二宝","昵称与简介跨重启保留")
    profile.nickname=String(repeating:"超",count:33)
    check(!store.saveProfile(profile),"个人资料长度受控，不破坏版式")
    let cloud=TopicCloud.words([TopicTotal(name:"劳动自由",value:5),TopicTotal(name:"哲学",value:3),TopicTotal(name:"研究方法",value:2)],size:CGSize(width:700,height:200),showNames:true)
    check(cloud.count==3,"主题词云展示真实主题分布")
    check(cloud.enumerated().allSatisfy {i,w in cloud.enumerated().allSatisfy {j,v in i==j || !w.rect.intersects(v.rect)}},"词云排版不重叠")
    let hidden=TopicCloud.words([TopicTotal(name:"私人研究方向",value:1)],size:CGSize(width:700,height:200),showNames:false)
    check(hidden.first?.name=="主题 1","词云默认可隐藏真实主题名称")
}
