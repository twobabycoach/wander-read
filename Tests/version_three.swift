import Foundation

func runVersionThreeChecks() throws {
    let root=FileManager.default.temporaryDirectory.appendingPathComponent("wander-link-tests-\(UUID().uuidString)")
    try FileManager.default.createDirectory(at:root,withIntermediateDirectories:true)
    let channel=root.appendingPathComponent("channel"),pdf=root.appendingPathComponent("含 空格 % #.pdf")
    // Enqueue only validates a local path. The receiving app separately parses the PDF.
    try Data("isolated path fixture".utf8).write(to:pdf)
    let id=UUID(),now=Date()
    let uri=try ResearchLink.enqueue(itemID:id,title:"测试文献",pdf:pdf,root:channel,now:now)
    check(uri.scheme=="pfr" && !uri.absoluteString.contains(pdf.path) && !uri.absoluteString.contains("token"),"唤起地址不携带 PDF 路径或配对令牌")
    let request=try ResearchLink.request(uri,root:channel,now:now)
    check(request.pdfPath==pdf.path && request.itemID==id.uuidString.lowercased(),"本地通信保留中文文件路径与收藏身份")
    rejects({_ = try ResearchLink.request(uri,root:channel,now:now.addingTimeInterval(301))},"过期请求不能冒充当前阅读选择")
    rejects({_ = try ResearchLink.request(URL(string:"pfr://prepare?id=../../outside")!,root:channel,now:now)},"通信入口拒绝路径穿越")
    rejects({_ = try ResearchLink.enqueue(itemID:id,title:"远程",pdf:URL(string:"https://example.com/a.pdf")!,root:channel)},"通信不把远程网址当本地 PDF")
    var foreign=request;foreign.token=UUID().uuidString
    let requestPath=channel.appendingPathComponent("requests/\(request.id).json")
    try ResearchLink.write(foreign,at:requestPath)
    rejects({_ = try ResearchLink.request(uri,root:channel,now:now)},"未配对请求拒绝处理")
    try ResearchLink.write(request,at:requestPath)
    let store=ReadingStore(directory:root.appendingPathComponent("library"))
    check(store.commit {$0.items=[ReadingItem(id:id,title:"测试文献",target:pdf.path)]},"通信测试使用独立资料库")
    try ResearchLink.acknowledge(request,root:channel)
    check(!FileManager.default.fileExists(atPath:requestPath.path),"研贴确认准备后才消费请求")
    store.pollResearchLink(root:channel)
    check(store.library.items[0].researchNoteURL==nil && (store.library.researchEvents ?? []).isEmpty,"准备 PDF 不冒充摘录保存或复习")
    let excerpt=UUID(),note="obsidian://pfr-excerpt?vault=Test&file=paper.md&id=\(excerpt.uuidString.lowercased())"
    try ResearchLink.saved(excerptID:excerpt,itemID:request.itemID,token:request.token,title:"测试",noteURL:note,root:channel)
    store.pollResearchLink(root:channel)
    check(store.library.items[0].researchNoteURL==note && store.library.researchEvents?.count==1,"Obsidian 保存回执落盘后出现返回笔记入口")
    check(store.library.sessions.isEmpty && store.library.items[0].choices==0,"摘录通信不产生虚假阅读选择")
    try ResearchLink.saved(excerptID:excerpt,itemID:request.itemID,token:request.token,title:"测试",noteURL:note,root:channel)
    store.pollResearchLink(root:channel)
    check(store.library.researchEvents?.count==1 && ResearchLink.updates(root:channel).isEmpty,"重复回执幂等消费")
    let reload=ReadingStore(directory:root.appendingPathComponent("library"))
    check(reload.library.items[0].researchNoteURL==note && reload.library.researchEvents?.count==1,"重启保留摘录入口与保存事件")
    try ResearchLink.saved(excerptID:UUID(),itemID:request.itemID,token:request.token,title:"测试",noteURL:"obsidian://open?file=other",root:channel)
    check(ResearchLink.updates(root:channel).isEmpty,"回执只能返回研贴摘录入口")
    let blockedPath=root.appendingPathComponent("blocked-library")
    try FileManager.default.createDirectory(at:blockedPath,withIntermediateDirectories:true)
    try LibraryIO.encode(store.library).write(to:blockedPath.appendingPathComponent("library.json"))
    let blocked=ReadingStore(directory:blockedPath)
    try FileManager.default.removeItem(at:blockedPath);try Data("file in place of directory".utf8).write(to:blockedPath)
    try ResearchLink.saved(excerptID:UUID(),itemID:request.itemID,token:request.token,title:"测试",noteURL:note,root:channel)
    blocked.pollResearchLink(root:channel)
    check(blocked.library.researchEvents?.count==1 && ResearchLink.updates(root:channel).count==1,"漫读保存失败保留回执供下次重试")
    let invalid=channel.appendingPathComponent("pair.json")
    try Data("broken".utf8).write(to:invalid)
    rejects({_ = try ResearchLink.token(at:channel,create:true)},"损坏配对配置保留原件而非静默重置")
    check(try String(contentsOf:invalid)=="broken","通信配置损坏不覆盖")
    var bad=store.library;bad.items[0].researchNoteURL="javascript:alert(1)"
    rejects({_ = try LibraryIO.decode(LibraryIO.encode(bad))},"备份拒绝无效摘录返回协议")
    bad=store.library;let duplicate=bad.researchEvents![0];bad.researchEvents?.append(duplicate)
    rejects({_ = try LibraryIO.decode(LibraryIO.encode(bad))},"备份拒绝重复保存事件")
}
