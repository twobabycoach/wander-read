import Foundation
func runCleanupChecks() throws {
    let root=FileManager.default.temporaryDirectory.appendingPathComponent("wander-cleanup-\(UUID().uuidString)")
    let store=ReadingStore(directory:root)
    let file=root.appendingPathComponent("original.md")
    try FileManager.default.createDirectory(at:root,withIntermediateDirectories:true)
    try Data("keep original".utf8).write(to:file)
    let a=ReadingItem(title:"导入一",target:file.path)
    let b=ReadingItem(title:"导入二",target:"https://example.com/cleanup")
    store.mergeItems([a,b],label:"测试导入")
    check(store.library.items.count==2 && store.library.items[0].importBatchID==store.library.items[1].importBatchID,"导入批次只关联本次新增项")
    store.mergeItems([a],label:"重复导入")
    check(store.library.items.count==2 && store.library.items[0].importBatchLabel=="测试导入","重复导入不改写已有批次")
    store.commit {$0.sessions=[ReadingSession(itemID:a.id,title:a.title,startedAt:Date(),stoppedAt:Date(),seconds:20)]}
    store.commit {$0.exposures=[ExposureEvent(itemID:a.id,date:Date(),source:"removed-source",isDemo:false,strategyName:"测试",branch:"测试")]}
    check(store.trashItems([a.id]),"所选入口可以移入回收站")
    check(!AttentionEngine.eligible(store.library.items[0],now:Date()) && !PriorityEngine.inScope(store.library.items[0],preferences:store.library.preferences),"回收站不进入推荐和研究对齐")
    check(JourneyAnalytics.realSessions(store.library).isEmpty,"回收站相关记录暂不计入回顾")
    check(!JourneyAnalytics.summary(store.library,days:30).sources.contains(where:{$0.name=="removed-source"}),"回收站曝光也从回顾统计排除")
    let resumed=ReadingStore(directory:root)
    check(resumed.library.items[0].trashedAt != nil,"回收站跨重启保存")
    check(resumed.restoreTrash([a.id]) && JourneyAnalytics.realSessions(resumed.library).count==1,"恢复时还原阅读历史")
    check(!resumed.purgeTrash([b.id]) && resumed.library.items.count==2,"永久清理不能作用于正常收藏")
    resumed.trashItems([a.id]);check(resumed.purgeTrash([a.id]),"永久清理仅移除已入回收站的所选项")
    check(resumed.library.items.count==1 && resumed.library.sessions.isEmpty,"永久清理同时移除关联记录")
    check(try String(contentsOf:file)=="keep original","清理绝不删除或改写原文件")
    let backups=try FileManager.default.contentsOfDirectory(at:root.appendingPathComponent("cleanup-backups"),includingPropertiesForKeys:nil)
    let before=try LibraryIO.decode(Data(contentsOf:backups[0]))
    check(backups.count==1 && before.items.count==2,"清理前独立完整备份可读取")
    check(try LibraryIO.decode(LibraryIO.encode(resumed.library)).items.count==1,"清理后的资料满足备份完整性约束")
    check(resumed.startVisit(b.id),"清理保护测试建立当前停留")
    check(!resumed.trashItems([b.id]) && resumed.library.items[0].trashedAt==nil,"正在阅读的条目需先收尾再清理")
    resumed.selectTheme(.night)
    let themed=ReadingStore(directory:root)
    check(themed.library.preferences.appTheme=="night" && Palette.theme == .night,"主题设置跨重启保存")
    themed.selectTheme(.paper)
    check(AppTheme.allCases.count==5,"五套应用主题全部直接可用")
}
